// Writes ultimate-team/data/cards.js: five cards (bronze to icon) for every character in
// game/assets/roster.json. Stats follow the role profiles below; edit the numbers here, not the output.
//   node ultimate-team/tools/make_cards.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const roster = JSON.parse(fs.readFileSync(path.join(root, 'game', 'assets', 'roster.json'), 'utf8'));

// rarity: target overall of the card (the stats are spread around it by role)
export const RARITIES = [
  { id: 'bronzo', name: 'Bronzo', ovr: 60 },
  { id: 'argento', name: 'Argento', ovr: 70 },
  { id: 'oro', name: 'Oro', ovr: 80 },
  { id: 'informa', name: 'In forma', ovr: 87 },
  { id: 'icona', name: 'Icona', ovr: 93 },
];

const ROLES = {
  difensore: { role: 'DIF', profile: { vel: -3, tir: -10, pas: 0, dri: -5, dif: 12, fis: 8 },
    weights: { dif: 0.35, fis: 0.2, vel: 0.15, pas: 0.15, dri: 0.1, tir: 0.05 } },
  centrocampista: { role: 'CEN', profile: { vel: 0, tir: -2, pas: 10, dri: 6, dif: 2, fis: -2 },
    weights: { pas: 0.3, dri: 0.25, vel: 0.15, dif: 0.1, tir: 0.1, fis: 0.1 } },
  ala: { role: 'ALA', profile: { vel: 10, tir: 0, pas: 3, dri: 8, dif: -10, fis: -6 },
    weights: { vel: 0.3, dri: 0.3, pas: 0.15, tir: 0.15, fis: 0.05, dif: 0.05 } },
  attaccante: { role: 'ATT', profile: { vel: 5, tir: 12, pas: -3, dri: 4, dif: -14, fis: 2 },
    weights: { tir: 0.35, vel: 0.25, dri: 0.2, fis: 0.1, pas: 0.1, dif: 0 } },
  portiere: { role: 'POR', profile: { tuf: 4, rif: 4, pre: 0, pos: 2, rin: -4 },
    weights: { rif: 0.25, tuf: 0.25, pos: 0.2, pre: 0.2, rin: 0.1 } },
};
// small team flavour so the two clubs differ
const TEAM_FLAVOUR = { celestini: { pas: 2, dri: 2, fis: -2, pre: 1 }, rivali: { fis: 2, dif: 2, pas: -2, tuf: 1 } };

function hash(s) { let h = 2166136261; for (const c of s) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619); } return h >>> 0; }
const clamp = (v) => Math.max(40, Math.min(99, Math.round(v)));

const cards = [];
for (const ch of roster.characters) {
  const [team, roleKey] = ch.id.split('_');
  const r = ROLES[roleKey];
  if (!r) continue;
  for (const rar of RARITIES) {
    const id = `${ch.id}_${rar.id}`;
    const stats = {};
    let h = hash(id);
    for (const [k, off] of Object.entries(r.profile)) {
      h = Math.imul(h ^ (h >>> 15), 2246822507) >>> 0;
      const jitter = (h % 5) - 2; // -2..+2
      stats[k] = rar.ovr + off + (TEAM_FLAVOUR[team]?.[k] || 0) + jitter;
    }
    // shift so the weighted overall lands on the rarity target
    const w = (s) => Object.entries(r.weights).reduce((a, [k, x]) => a + s[k] * x, 0);
    const shift = rar.ovr - w(stats);
    for (const k in stats) stats[k] = clamp(stats[k] + shift);
    cards.push({ id, char: ch.id, name: ch.name, team: team[0].toUpperCase() + team.slice(1), role: r.role,
      gk: r.role === 'POR', rarity: rar.id, ovr: Math.round(w(stats)), stats });
  }
}

const out = path.join(root, 'ultimate-team', 'data', 'cards.js');
fs.writeFileSync(out, `// Generated by ultimate-team/tools/make_cards.mjs from game/assets/roster.json: edit that script, not this file.
export const RARITIES = ${JSON.stringify(RARITIES)};
export const CARDS = [
${cards.map((c) => '  ' + JSON.stringify(c)).join(',\n')},
];
`);
console.log(`wrote ${out}: ${cards.length} cards`);
